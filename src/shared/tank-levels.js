  const SIZE = 26;
  const CELL = { '.': 0, '#': 1, '@': 2, '~': 3, '%': 4, '-': 5, T: 6 };
  const TILE = { EMPTY: 0, BRICK: 1, STEEL: 2, WATER: 3, BUSH: 4, ICE: 5, TELE: 6, BASE: 7 };

  // Co-op layout: enemy gates on top, base and players at the bottom.
  const GATES = [[0, 0], [12, 0], [24, 0]];
  const PLAYER_START = [[8, 24], [16, 24]];
  const BASE_AT = [12, 24];

  // Expands a 13 x 13 map to the 26 x 26 grid and clears the reserved places.
  function build(rows, mode = 'coop') {
    const g = Array.from({ length: SIZE }, () => new Array(SIZE).fill(0));
    const tele = [];
    for (let cy = 0; cy < 13; cy++) {
      const row = (rows[cy] || '').padEnd(13, '.');
      for (let cx = 0; cx < 13; cx++) {
        const v = CELL[row[cx]] ?? 0;
        for (let dy = 0; dy < 2; dy++) for (let dx = 0; dx < 2; dx++) g[cy * 2 + dy][cx * 2 + dx] = v === TILE.TELE ? 0 : v;
        if (v === TILE.TELE) tele.push([cx * 2, cy * 2]);
      }
    }
    const clear = (x, y, w = 2, h = 2) => { for (let j = y; j < y + h; j++) for (let i = x; i < x + w; i++) if (g[j] && g[j][i] !== undefined) g[j][i] = 0; };
    const bases = [];
    if (mode === 'coop') {
      for (const [x, y] of GATES) clear(x, y);
      for (const [x, y] of PLAYER_START) clear(x, y);
      clear(10, 22, 6, 4);
      // The base and its brick ring.
      for (let i = 11; i <= 14; i++) g[23][i] = TILE.BRICK;
      for (const y of [24, 25]) { g[y][11] = TILE.BRICK; g[y][14] = TILE.BRICK; }
      bases.push({ x: 12, y: 24, team: 0 });
    } else {
      // Versus: bases at the left and right middle, players beside them.
      clear(0, 10, 4, 6);
      clear(22, 10, 4, 6);
      bases.push({ x: 0, y: 12, team: 0 }, { x: 24, y: 12, team: 1 });
      for (const b of bases) {
        const ring = b.team === 0 ? 2 : 23;
        for (let y = 11; y <= 14; y++) g[y][ring] = TILE.BRICK;
        for (let i = 0; i < 4; i++) { const x = b.team === 0 ? i : 22 + i; g[11][x] = TILE.BRICK; g[14][x] = TILE.BRICK; }
        clear(b.x, b.y);
      }
      clear(12, 0); clear(12, 24); // drone gates, top and bottom middle
    }
    for (const b of bases) for (let dy = 0; dy < 2; dy++) for (let dx = 0; dx < 2; dx++) g[b.y + dy][b.x + dx] = TILE.BASE;
    // Teleporter pads, linked in pairs.
    const pads = [];
    for (let i = 0; i + 1 < tele.length; i += 2) pads.push({ a: tele[i], b: tele[i + 1] });
    return { grid: g, pads, bases };
  }

  // Can a 2 x 2 tank get from a to b? Bricks and bushes count as passable
  // (bricks can be shot away); steel, water and the base do not.
  function reachable(grid, from, to) {
    const ok = (x, y) => {
      if (x < 0 || y < 0 || x > SIZE - 2 || y > SIZE - 2) return false;
      for (let dy = 0; dy < 2; dy++) for (let dx = 0; dx < 2; dx++) {
        const v = grid[y + dy][x + dx];
        if (v === TILE.STEEL || v === TILE.WATER || v === TILE.BASE) return false;
      }
      return true;
    };
    const seen = new Set([`${from[0]},${from[1]}`]);
    const q = [from];
    while (q.length) {
      const [x, y] = q.shift();
      if (Math.abs(x - to[0]) <= 1 && Math.abs(y - to[1]) <= 1) return true;
      for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
        const nx = x + dx;
        const ny = y + dy;
        const k = `${nx},${ny}`;
        if (!seen.has(k) && ok(nx, ny)) { seen.add(k); q.push([nx, ny]); }
      }
    }
    return false;
  }

  // How hard each level is: how many enemies, which kinds, how many at once.
  // Smooth growth so every level stays winnable; kinds: scout, trooper, heavy, rocket.
  function waveFor(level) {
    const L = Math.max(1, Math.min(50, level));
    const t = (L - 1) / 49;
    const count = Math.round(8 + 12 * t); // 8 -> 20 enemies
    const atOnce = Math.min(5, 2 + Math.floor(L / 10)); // 2 -> 5 on the field
    const mix = {
      scout: 0.35 - 0.1 * t,
      trooper: 0.55 - 0.3 * t,
      heavy: 0.05 + 0.25 * t,
      rocket: Math.max(0, -0.05 + 0.2 * t),
    };
    // Ice and teleporter levels are already tricky: a little gentler.
    const map = COOP[L - 1].join('');
    const gentle = (map.split('-').length > 40 || map.includes('T')) ? 0.85 : 1;
    return { count: Math.round(count * gentle), atOnce, mix, fire: 0.6 + 0.4 * t, speed: 0.88 + 0.17 * t };
  }

