# Builds src/renderer/pieces.css from the chess piece sprite in
# build/third-party/chess-pieces-cburnett.svg (run: python3 scripts/make-pieces.py).
#
# Chess pieces by Colin M.L. Burnett (Cburnett) and Rfc1394, Wikimedia Commons,
# CC BY-SA 3.0 (https://creativecommons.org/licenses/by-sa/3.0/), via cm-chessboard.
import base64
import re

SRC = 'build/third-party/chess-pieces-cburnett.svg'
OUT = 'src/renderer/pieces.css'

svg = open(SRC, encoding='utf-8').read()
svg = re.sub(r'<!--.*?-->', '', svg, flags=re.S)


def element(piece_id):
    """Returns the full <g id="..."> element, including nested groups."""
    start = svg.index(f'<g id="{piece_id}"')
    depth = 0
    for m in re.finditer(r'<g\b[^>]*?(/?)>|</g>', svg[start:]):
        if m.group(0).startswith('</g'):
            depth -= 1
        elif not m.group(1):
            depth += 1
        if depth == 0:
            return svg[start:start + m.end()]
    raise ValueError(piece_id)


lines = [
    '/* Chess pieces by Colin M.L. Burnett (Cburnett) and Rfc1394, Wikimedia Commons,',
    '   licensed CC BY-SA 3.0 (https://creativecommons.org/licenses/by-sa/3.0/).',
    '   Generated by scripts/make-pieces.py - do not edit by hand. */',
]
for color in 'wb':
    for kind in 'kqrbnp':
        g = element(color + kind)
        doc = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 40 40">{g}</svg>'
        b64 = base64.b64encode(doc.encode()).decode()
        lines.append(f'.pc.{color}{kind} {{ background-image: url("data:image/svg+xml;base64,{b64}"); }}')
open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('wrote', OUT)
